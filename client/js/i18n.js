const i18n = {
  locale: localStorage.getItem('botdz_locale') || 'ar',
  t(key) {
    const dict = I18N[this.locale] || I18N.ar;
    return dict[key] || (I18N.en[key]) || key;
  },
  setLocale(loc) {
    if (!I18N[loc]) return;
    this.locale = loc;
    localStorage.setItem('botdz_locale', loc);
    document.documentElement.setAttribute('lang', loc);
    document.documentElement.setAttribute('dir', I18N[loc].dir);
    document.body.classList.toggle('rtl', I18N[loc].dir === 'rtl');
  },
  dict() { return I18N[this.locale] || I18N.ar; }
};
i18n.setLocale(i18n.locale);
